package uk.gov.moj.cp.retrieval.service;

import static uk.gov.hmcts.cp.openapi.model.AnswerGenerationStatus.ANSWER_GENERATED;
import static uk.gov.hmcts.cp.openapi.model.AnswerGenerationStatus.ANSWER_GENERATION_FAILED;
import static uk.gov.moj.cp.ai.util.EnvVarUtil.getRequiredEnv;
import static uk.gov.moj.cp.ai.util.StringUtil.isNullOrEmpty;
import static uk.gov.moj.cp.ai.util.StringUtil.unescapeContent;

import uk.gov.moj.cp.ai.client.ChatServiceFactory;
import uk.gov.moj.cp.ai.exception.ChatServiceException;
import uk.gov.moj.cp.ai.model.ChunkedEntry;
import uk.gov.moj.cp.ai.service.ChatService;
import uk.gov.moj.cp.ai.util.ChunkFormatterUtility;
import uk.gov.moj.cp.retrieval.exception.CitationDegradedException;
import uk.gov.moj.cp.retrieval.model.CitationGuardMode;
import uk.gov.moj.cp.retrieval.model.CitationScope;
import uk.gov.moj.cp.retrieval.model.LlmResponse;
import uk.gov.moj.cp.retrieval.service.CitationProcessor.CitationOutcome;
import uk.gov.moj.cp.retrieval.service.CitationProcessor.ValidationCounts;

import java.util.List;
import java.util.Locale;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

public class ResponseGenerationService {

    private static final Logger LOGGER = LoggerFactory.getLogger(ResponseGenerationService.class);

    static final String LLM_RESPONSE_NO_DATA_AVAILABLE = "No data available matching the query.";
    public static final String LLM_RESPONSE_FAILURE_TO_GENERATE = "No response generated by the service.";

    private final ChatService chatService;
    private final CitationProcessor citationProcessor;
    private final ChunkFormatterUtility chunkFormatterUtility;
    private final UserInstructionService userInstructionService;

    private final String systemPromptTemplate;
    private final CitationGuardMode guardMode;

    public ResponseGenerationService() {
        String endpoint = getRequiredEnv("AZURE_OPENAI_ENDPOINT");
        String deploymentName = getRequiredEnv("AZURE_OPENAI_CHAT_DEPLOYMENT_NAME");

        chatService = ChatServiceFactory.getInstance(endpoint, deploymentName);
        citationProcessor = new CitationProcessor();
        chunkFormatterUtility = new ChunkFormatterUtility();
        userInstructionService = new UserInstructionService();

        systemPromptTemplate = unescapeContent(getRequiredEnv("RESPONSE_GENERATION_SYSTEM_PROMPT"));
        guardMode = CitationGuardMode.fromEnv();
    }

    public ResponseGenerationService(final ChatService chatService, final CitationProcessor citationProcessor, final ChunkFormatterUtility chunkFormatterUtility, final UserInstructionService userInstructionService, final String systemPromptTemplate) {
        this(chatService, citationProcessor, chunkFormatterUtility, userInstructionService, systemPromptTemplate,
                CitationGuardMode.fromEnv());
    }

    ResponseGenerationService(final ChatService chatService, final CitationProcessor citationProcessor,
                              final ChunkFormatterUtility chunkFormatterUtility,
                              final UserInstructionService userInstructionService,
                              final String systemPromptTemplate,
                              final CitationGuardMode guardMode) {
        this.chatService = chatService;
        this.citationProcessor = citationProcessor;
        this.chunkFormatterUtility = chunkFormatterUtility;
        this.userInstructionService = userInstructionService;
        this.systemPromptTemplate = systemPromptTemplate;
        this.guardMode = guardMode;
    }

    /**
     * Generates the answer with a single LLM attempt. The answer's citations are validated against
     * a {@link CitationScope} built once from {@code chunkedEntries} — the same list rendered into
     * the prompt — so each attempt is checked against its own retrieval. The citation guard
     * evaluates every answer regardless of mode. When the guard is enforcing ({@code CITATION_GUARD_MODE} != OFF) and
     * the answer comes back citation-degraded, a {@link CitationDegradedException} carrying the
     * degraded answer is thrown — retry and exhaustion policy belong to the caller: the async
     * queue worker retries via queue redelivery; the synchronous path applies the policy
     * immediately. With the guard OFF a citation-degraded answer is returned as
     * {@code ANSWER_GENERATED} with the guard reason attached, so the degradation is still
     * recorded (reason column, logs) without any retry or rejection.
     */
    public LlmResponse generateResponse(final String userQuery, final List<ChunkedEntry> chunkedEntries,
                                        final String userQueryPrompt) throws ChatServiceException {
        if (null == chunkedEntries || chunkedEntries.isEmpty()) {
            LOGGER.warn("No matching data from search database retrieved for the query");
            return new LlmResponse(LLM_RESPONSE_NO_DATA_AVAILABLE, LLM_RESPONSE_NO_DATA_AVAILABLE, ANSWER_GENERATED);
        }

        LOGGER.info("Generating LLM response");

        // Built once from the same list rendered into the prompt; citations are validated against it.
        final CitationScope citationScope = CitationScope.from(chunkedEntries);

        final String formattedChunks = chunkFormatterUtility.buildChunkContext(chunkedEntries);
        LOGGER.info("Constructed retrieved contexts, has {} characters", formattedChunks.length());

        final String userInstruction = userInstructionService.buildUserInstruction(userQuery, userQueryPrompt, formattedChunks);

        return chatService.callModel(systemPromptTemplate, userInstruction, String.class)
                .filter(rawLlmResponse -> !isNullOrEmpty(rawLlmResponse))
                .map(rawLlmResponse -> toGuardedResponse(rawLlmResponse, citationScope))
                .orElseGet(() -> {
                    LOGGER.warn("LLM returned no response.");
                    return new LlmResponse(LLM_RESPONSE_FAILURE_TO_GENERATE, LLM_RESPONSE_FAILURE_TO_GENERATE, ANSWER_GENERATION_FAILED);
                });
    }

    /**
     * Applies the citation guard to one raw answer, after validating its citations against
     * {@code citationScope}. A degraded answer — including one whose every citation entry failed
     * validation, so nothing rendered — throws {@link CitationDegradedException} when the guard is
     * enforcing; with the guard OFF it is returned as generated, carrying the guard reason
     * (which ends {@code invalid=N}, the entries dropped by validation) so the degradation is
     * still recorded. An accepted answer that lost some entries or pages to validation keeps a
     * null reason (the reason column is reserved for real degradation) and logs one counts-only
     * WARN.
     */
    private LlmResponse toGuardedResponse(final String rawLlmResponse, final CitationScope citationScope) {
        final CitationOutcome outcome = citationProcessor.processCitations(rawLlmResponse, citationScope);
        if (isAcceptable(outcome)) {
            LOGGER.info("Citation guard [{}]: accepted {} — rendered={}, inlineMarkers={}, stripped={}, jsonBlock={}, formattedLength={} chars, invalid={}, trimmedPages={}",
                    guardMode.name().toLowerCase(Locale.ROOT),
                    outcome.renderedCitations() >= 1 ? "cited answer" : "no-evidence refusal",
                    outcome.renderedCitations(), outcome.inlineMarkers(), outcome.strippedMarkers(),
                    outcome.jsonBlockPresent(), outcome.formattedText().length(),
                    outcome.invalidEntries(), outcome.trimmedPages());
            warnIfPartlyInvalid(outcome);
            return new LlmResponse(rawLlmResponse, outcome.formattedText(), ANSWER_GENERATED);
        }
        // Mode-prefixed so the reason column alone tells a first-attempt OFF degradation apart
        // from a DELIVER/REJECT outcome reached after the caller's retries.
        final String reason = String.format(
                "[guard=%s] Citations missing: jsonBlock=%s, inlineMarkers=%d, rendered=%d, stripped=%d, invalid=%d",
                guardMode.name().toLowerCase(Locale.ROOT), outcome.jsonBlockPresent(), outcome.inlineMarkers(),
                outcome.renderedCitations(), outcome.strippedMarkers(), outcome.invalidEntries());
        if (guardMode == CitationGuardMode.OFF) {
            LOGGER.warn("Citation guard (off): delivering citation-degraded answer without retry — {}.", reason);
            return new LlmResponse(rawLlmResponse, outcome.formattedText(), ANSWER_GENERATED, reason);
        }
        LOGGER.warn("Citation guard: degraded answer — {}.", reason);
        throw new CitationDegradedException(reason, rawLlmResponse, outcome.formattedText());
    }

    /**
     * Partial invalidity — at least one citation rendered, but validation dropped entries or
     * trimmed pages — is accepted without a reason and surfaced by exactly one WARN. Counts only:
     * correlation comes from the MDC, and the cause labels deliberately avoid a literal
     * {@code documentId=} token so log searches for it stay clean.
     */
    private static void warnIfPartlyInvalid(final CitationOutcome outcome) {
        if (outcome.renderedCitations() < 1 || (outcome.invalidEntries() == 0 && outcome.trimmedPages() == 0)) {
            return;
        }
        final ValidationCounts counts = outcome.validation();
        LOGGER.warn("Citation validation: answer accepted after removing invalid citation entries or pages — "
                        + "entries={}, invalid={} [causeCitationId={}, causeDocument={}, causeFilename={}, causePages={}], "
                        + "trimmedPages={}, rendered={}",
                counts.factMapEntries(), counts.invalidEntries(), counts.noCitationId(), counts.invalidDocumentId(),
                counts.invalidFileName(), counts.noValidPage(), counts.trimmedPages(), outcome.renderedCitations());
    }

    /**
     * An answer is citation-acceptable when it carries at least one rendered citation, or when
     * it is a deliberate no-evidence refusal (block present, empty array, no markers written).
     * Evaluated in every guard mode; the mode only decides what happens to an unacceptable one.
     */
    private boolean isAcceptable(final CitationOutcome outcome) {
        if (outcome.renderedCitations() >= 1) {
            return true;
        }
        return outcome.jsonBlockPresent() && outcome.emptyFactMap() && outcome.inlineMarkers() == 0;
    }
}